import fs from 'node:fs';
import readline from 'node:readline';
const tokenPath=process.argv[3];
const info=fs.lstatSync(tokenPath);
if (!info.isFile() || info.isSymbolicLink() || (info.mode & 0o777)!==0o600 || info.uid!==process.getuid()) throw Error('private capability file required');
const token=fs.readFileSync(tokenPath,'utf8').trim();
if (!/^[A-Za-z0-9_-]{32,128}$/.test(token)) throw Error('invalid capability format');
const ws=new WebSocket(process.argv[2],{headers:{Authorization:`Bearer ${token}`}});
let pending=[];let bytes=0;
const fail=()=>{process.stderr.write('protocol transport stopped\n');process.exit(1);};
ws.addEventListener('open',()=>{for (const line of pending) ws.send(line);pending=[];bytes=0;});
ws.addEventListener('message',({data})=>{const text=String(data);if(Buffer.byteLength(text)>16*1024*1024) return fail(); if(process.stdout.writableLength>32*1024*1024)return fail();process.stdout.write(text+'\n');});
ws.addEventListener('error',fail);
ws.addEventListener('close',()=>process.exit());
const input=readline.createInterface({input:process.stdin});
input.on('line',line=>{if(Buffer.byteLength(line)>65536)return fail();if(ws.readyState===WebSocket.OPEN)ws.send(line);else if(ws.readyState===WebSocket.CONNECTING){bytes+=Buffer.byteLength(line);if(bytes>65536)return fail();pending.push(line);}else fail();});
input.on('close',()=>{ws.close();setTimeout(()=>process.exit(),100).unref();});
